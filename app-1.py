"""Safe strategy DSL.

Strategies are plain JSON (no executable code), which makes it safe to accept
specs generated by an LLM. A spec looks like:

{
  "name": "EMA pullback in trend",
  "rationale": "Buy dips to the fast EMA while the slow EMA trends up.",
  "long":  [ {"a": {"ind": "ema", "n": 50}, "op": ">", "b": {"ind": "ema", "n": 200}},
             {"a": {"ind": "rsi", "n": 14}, "op": "crosses_above", "b": 40} ],
  "short": [ ... ],
  "sl_atr": 1.5, "tp_atr": 2.0, "atr_n": 14, "max_bars": 60
}

Conditions inside a side are AND-ed. Signals are evaluated on the close of a
bar and executed at the next bar's open.
"""

