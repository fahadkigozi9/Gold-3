MAX_CONDITIONS = 6


class SpecError(ValueError):
    """Raised when a strategy spec cannot be repaired into a valid one."""


# --------------------------------------------------------------------------- validation
def _clamp_param(val: Any, default, lo, hi, typ):
    try:
        v = float(val)
        if not math.isfinite(v):
            raise ValueError
    except (TypeError, ValueError):
        v = float(default)
    v = min(max(v, lo), hi)
    return int(round(v)) if typ is int else round(float(v), 3)


def _clean_operand(op: Any) -> Any:
    if isinstance(op, bool):
        raise SpecError("boolean operand not allowed")
    if isinstance(op, (int, float)):
        if not math.isfinite(op):
            raise SpecError("non-finite constant")
        return float(op)
    if isinstance(op, str):  # tolerate bare indicator name e.g. "close"
        op = {"ind": op}
    if not isinstance(op, dict):
        raise SpecError(f"bad operand: {op!r}")
    name = str(op.get("ind", op.get("indicator", ""))).strip().lower()
    if name not in INDICATORS:
        raise SpecError(f"unknown indicator '{name}'")
    clean: dict[str, Any] = {"ind": name}
    for p, (default, lo, hi, typ) in INDICATORS[name].items():
        clean[p] = _clamp_param(op.get(p, default), default, lo, hi, typ)
    if name == "macd_hist" and clean["slow"] <= clean["fast"]:
        clean["slow"] = min(100, clean["fast"] + 5)
    return clean


def _clean_condition(c: Any) -> dict:
    if not isinstance(c, dict):
        raise SpecError(f"bad condition: {c!r}")
    a = c.get("a", c.get("left", c.get("lhs")))
    b = c.get("b", c.get("right", c.get("rhs")))
    op = str(c.get("op", c.get("operator", ""))).strip().lower()
    op = _OP_ALIASES.get(op, op)
    if op not in OPS:
        raise SpecError(f"bad operator '{op}'")
    if a is None or b is None:
        raise SpecError("condition needs both a and b")
    a, b = _clean_operand(a), _clean_operand(b)
    if not isinstance(a, dict) and not isinstance(b, dict):
        raise SpecError("condition compares two constants")
    return {"a": a, "op": op, "b": b}


def _num(x: Any, default: float, lo: float, hi: float) -> float:
    try:
        v = float(x)
        if not math.isfinite(v):
            raise ValueError
    except (TypeError, ValueError):
        v = default
    return round(min(max(v, lo), hi), 3)


def validate_spec(raw: Any) -> dict:
    """Return a cleaned copy of ``raw`` or raise SpecError."""
    if not isinstance(raw, dict):
        raise SpecError("spec must be an object")
    sides: dict[str, list] = {}
    for side in ("long", "short"):
        conds = raw.get(side) or raw.get(f"{side}_entry") or raw.get(f"entry_{side}") or []
        if not isinstance(conds, list):
            raise SpecError(f"'{side}' must be a list")
        cleaned = []
        for c in conds[:MAX_CONDITIONS]:
            cleaned.append(_clean_condition(c))
        sides[side] = cleaned
    if not sides["long"] and not sides["short"]:
        raise SpecError("spec has no entry conditions")
    name = str(raw.get("name") or "Unnamed strategy").strip()[:60]
    return {
        "name": name,
        "rationale": str(raw.get("rationale") or "")[:400],
        "long": sides["long"],
        "short": sides["short"],
        "sl_atr": _num(raw.get("sl_atr"), 1.5, 0.2, 8.0),
        "tp_atr": _num(raw.get("tp_atr"), 2.0, 0.2, 15.0),
        "atr_n": int(_num(raw.get("atr_n"), 14, 5, 50)),
        "max_bars": int(_num(raw.get("max_bars"), 100, 1, 1000)),
    }


def spec_hash(spec: dict) -> str:
    core = {k: spec[k] for k in ("long", "short", "sl_atr", "tp_atr", "atr_n", "max_bars")}
    return hashlib.md5(json.dumps(core, sort_keys=True).encode()).hexdigest()[:12]


def describe(spec: dict) -> str:
    def fmt(o):
        if not isinstance(o, dict):
            return f"{o:g}"
        ps = ",".join(str(o[p]) for p in INDICATORS[o["ind"]])
        return f"{o['ind']}({ps})" if ps else o["ind"]

    def side(conds):
        return " AND ".join(f"{fmt(c['a'])} {c['op']} {fmt(c['b'])}" for c in conds) or "-"

    return (f"LONG: {side(spec['long'])}\nSHORT: {side(spec['short'])}\n"
            f"SL {spec['sl_atr']}xATR({spec['atr_n']}), TP {spec['tp_atr']}xATR, "
            f"time stop {spec['max_bars']} bars")


