class SeriesCache:
    """Computes and memoises indicator series for one OHLC DataFrame."""

    def __init__(self, df: pd.DataFrame):
        self.df = df
        self._store: dict[tuple, pd.Series] = {}

    def get(self, name: str, **params) -> pd.Series:
        key = (name, tuple(sorted(params.items())))
        if key not in self._store:
            self._store[key] = self._compute(name, **params)
        return self._store[key]

    def _compute(self, name: str, **p) -> pd.Series:
        d = self.df
        o, h, l, c = d["open"], d["high"], d["low"], d["close"]
        if name in ("close", "open", "high", "low"):
            return d[name]
        if name == "hour":
            return pd.Series(d.index.hour.astype(float), index=d.index)
        if name == "dow":
            return pd.Series(d.index.dayofweek.astype(float), index=d.index)
        if name == "ema":
            return ind.ema(c, p["n"])
        if name == "sma":
            return ind.sma(c, p["n"])
        if name == "rsi":
            return ind.rsi(c, p["n"])
        if name == "atr":
            return ind.atr(h, l, c, p["n"])
        if name == "adx":
            return ind.adx(h, l, c, p["n"])
        if name == "stoch_k":
            return ind.stoch_k(h, l, c, p["n"])
        if name == "roc":
            return ind.roc(c, p["n"])
        if name == "zscore":
            return ind.zscore(c, p["n"])
        if name == "macd_hist":
            return ind.macd_hist(c, p["fast"], p["slow"], p["signal"])
        if name == "bb_upper":
            return ind.bollinger(c, p["n"], p["k"])[0]
        if name == "bb_lower":
            return ind.bollinger(c, p["n"], p["k"])[1]
        if name == "donchian_high":
            return ind.donchian_high(h, p["n"])
        if name == "donchian_low":
            return ind.donchian_low(l, p["n"])
        if name == "dist_ema_atr":
            return (c - ind.ema(c, p["n"])) / self.get("atr", n=14).replace(0.0, np.nan)
        if name == "body_atr":
            return (c - o) / self.get("atr", n=14).replace(0.0, np.nan)
        if name == "range_atr":
            return (h - l) / self.get("atr", n=14).replace(0.0, np.nan)
        raise SpecError(f"unknown indicator '{name}'")

    def operand(self, op):
        if isinstance(op, dict):
            return self.get(op["ind"], **{k: v for k, v in op.items() if k != "ind"})
        return float(op)


def _eval_condition(cache: SeriesCache, cond: dict) -> np.ndarray:
    a, b, op = cache.operand(cond["a"]), cache.operand(cond["b"]), cond["op"]
    n = len(cache.df)

    def arr(x):
        return x.to_numpy(dtype=float) if isinstance(x, pd.Series) else np.full(n, x, dtype=float)

    av, bv = arr(a), arr(b)
    with np.errstate(invalid="ignore"):
        if op == ">":
            res = av > bv
        elif op == "<":
            res = av < bv
        elif op == ">=":
            res = av >= bv
        elif op == "<=":
            res = av <= bv
        else:
            ap, bp = np.roll(av, 1), np.roll(bv, 1)
            ap[0] = bp[0] = np.nan
            res = (av > bv) & (ap <= bp) if op == "crosses_above" else (av < bv) & (ap >= bp)
    return res


def signals(spec: dict, cache: SeriesCache) -> np.ndarray:
    """Return int8 array: +1 long, -1 short, 0 none (conflicts cancel)."""
    n = len(cache.df)
    out = {}
    for side in ("long", "short"):
        conds = spec[side]
        if not conds:
            out[side] = np.zeros(n, dtype=bool)
            continue
        m = np.ones(n, dtype=bool)
        for c in conds:
            m &= _eval_condition(cache, c)
        out[side] = m
    sig = np.zeros(n, dtype=np.int8)
    sig[out["long"] & ~out["short"]] = 1
    sig[out["short"] & ~out["long"]] = -1
    return sig


def clone(spec: dict) -> dict:
    return copy.deepcopy(spec)

